-- 057_fee_invoice_amount_repair.sql
--
-- Normalises every unit-registration invoice to the amount it should bill:
--
--     billed = SUM(items.amount) - discount
--
-- Migration 056 only repaired invoices that were billed *below* their items.
-- That left a handful of invoices billed above their items, for example:
--   * units were deregistered but the parent total kept the old figure
--   * a discount was applied after the units were billed, so `amount` still
--     held the pre-discount total and the student looked wrongly indebted
--   * a duplicated unit list was left in the generated description
--
-- Those invoices overstate the college's expected fees and outstanding
-- balances in the fees pages and reports, so this migration re-derives them.
--
-- Safety rules:
--   * only invoices generated by unit registration are touched
--   * amount_paid is never modified (overpayments stay as credits)
--   * invoices with no items keep their amount; only their status is aligned
--   * runs recalculate_fee_payment_totals() from migration 056

DO $$
DECLARE
  v_fee RECORD;
  v_repaired INTEGER := 0;
BEGIN
  IF to_regprocedure('public.recalculate_fee_payment_totals(uuid)') IS NULL THEN
    RAISE EXCEPTION
      'Apply supabase/migrations/056_fee_invoice_consistency.sql before this migration.';
  END IF;

  -- Rebuild amount, original_amount, status and description from the units.
  FOR v_fee IN
    SELECT fp.id
    FROM public.fee_payments fp
    WHERE COALESCE(fp.description, '') LIKE 'Unit registration%'
      AND EXISTS (
        SELECT 1 FROM public.fee_payment_items i WHERE i.fee_payment_id = fp.id
      )
  LOOP
    PERFORM public.recalculate_fee_payment_totals(v_fee.id);
    v_repaired := v_repaired + 1;
  END LOOP;

  -- Unit invoices whose units were all deregistered keep their retained
  -- amount, but the payment status must still match what was received.
  UPDATE public.fee_payments fp
  SET status = (
    CASE
      WHEN fp.amount = 0 AND COALESCE(fp.amount_paid, 0) = 0 THEN 'waived'
      WHEN COALESCE(fp.amount_paid, 0) >= fp.amount THEN 'paid'
      WHEN COALESCE(fp.amount_paid, 0) > 0 THEN 'partial'
      ELSE 'pending'
    END
  )::public.payment_status
  WHERE COALESCE(fp.description, '') LIKE 'Unit registration%'
    AND NOT EXISTS (
      SELECT 1 FROM public.fee_payment_items i WHERE i.fee_payment_id = fp.id
    )
    AND fp.status IS DISTINCT FROM (
      CASE
        WHEN fp.amount = 0 AND COALESCE(fp.amount_paid, 0) = 0 THEN 'waived'
        WHEN COALESCE(fp.amount_paid, 0) >= fp.amount THEN 'paid'
        WHEN COALESCE(fp.amount_paid, 0) > 0 THEN 'partial'
        ELSE 'pending'
      END
    )::public.payment_status;

  RAISE NOTICE 'Repaired % unit invoices from their line items.', v_repaired;
END $$;

-- Verification: these should all return zero rows.
-- 1. Unit invoices with items whose amount is not items - discount.
SELECT fp.id, fp.amount, items.items_total, COALESCE(fp.discount_amount, 0) AS discount
FROM public.fee_payments fp
JOIN (
  SELECT fee_payment_id, SUM(amount) AS items_total
  FROM public.fee_payment_items
  GROUP BY fee_payment_id
) items ON items.fee_payment_id = fp.id
WHERE COALESCE(fp.description, '') LIKE 'Unit registration%'
  AND ABS(fp.amount - GREATEST(items.items_total - COALESCE(fp.discount_amount, 0), 0)) > 0.01;

-- 2. Invoices whose status contradicts the money received.
SELECT fp.id, fp.amount, fp.amount_paid, fp.status
FROM public.fee_payments fp
WHERE COALESCE(fp.description, '') LIKE 'Unit registration%'
  AND fp.status IS DISTINCT FROM (
    CASE
      WHEN fp.amount = 0 AND COALESCE(fp.amount_paid, 0) = 0 THEN 'waived'
      WHEN COALESCE(fp.amount_paid, 0) >= fp.amount THEN 'paid'
      WHEN COALESCE(fp.amount_paid, 0) > 0 THEN 'partial'
      ELSE 'pending'
    END
  )::public.payment_status;
